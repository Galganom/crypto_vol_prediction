"""Audit saved forecasts and regenerate manuscript tables/figures without training.

Run from any directory: .venv/bin/python paper/build_artifacts.py
Only paper/generated and paper/figures are written. Inputs are never modified.
"""
from pathlib import Path
import hashlib
import json
import os
import sys
import warnings

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
os.environ.setdefault("MPLCONFIGDIR", "/tmp/crypto-paper-matplotlib")
sys.path.insert(0, str(ROOT))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import norm
import torch
from main_model_common import tag_based_recap_mask, WINDOWS, cfg
from main_model_cryptobert import CryptoBertMainModel

EPS = 1e-10
MODELS = {"har": "HAR", "egarch": "EGARCH", "egarch_ned": "EGARCH+NED",
          "ts_mlp": "TS MLP", "main_model": "Main Model"}
DISPLAY = {"TS MLP": "TS-only", "Main Model": "NED"}
GEN = PAPER / "generated"
FIG = PAPER / "figures"
GEN.mkdir(parents=True, exist_ok=True)
FIG.mkdir(parents=True, exist_ok=True)
torch.set_num_threads(2)
inputs = set()


def source(path):
    path = ROOT / path
    inputs.add(path)
    return path


def metrics(pred, actual):
    # Preserve the archived forecast dtype, as compute_metrics does in training.
    error = np.log(actual + EPS) - np.log(pred + EPS)
    ratio = (actual + EPS) / (pred + EPS)
    mse = error ** 2
    qlike = ratio - np.log(ratio) - 1
    logactual = np.log(actual + EPS)
    median = np.median(actual)
    return dict(MSE=mse.mean(), QLIKE=qlike.mean(),
                R2=1 - mse.sum() / ((logactual - logactual.mean()) ** 2).sum(),
                DA=np.mean((actual > median) == (pred > median))), mse, qlike


def dm(first, second, bandwidth):
    # Independent transcription of the repository's Bartlett-HAC normal test.
    d = np.asarray(first) - np.asarray(second)
    centered = d - d.mean()
    longrun = np.mean(centered ** 2)
    for lag in range(1, bandwidth + 1):
        longrun += 2 * (1 - lag / (bandwidth + 1)) * np.mean(centered[lag:] * centered[:-lag])
    stat = d.mean() / np.sqrt(longrun / len(d))
    return float(stat), float(2 * norm.sf(abs(stat)))


def table(name, columns, heading, rows):
    text = ["% Generated by paper/build_artifacts.py; do not edit.",
            r"\begin{tabular}{" + columns + "}", r"\toprule", heading + r" \\", r"\midrule"]
    text += [" & ".join(str(cell) for cell in row) + r" \\" for row in rows]
    text += [r"\bottomrule", r"\end{tabular}", ""]
    (GEN / name).write_text("\n".join(text))


def pformat(p):
    return r"$<0.001$" if p < .001 else f"{p:.3f}"


def main():
    news = pd.read_parquet(source("data/news/processed_news.parquet"))
    rows, dmrows, splitrows, corp, parameters, checks = [], [], [], [], [], []
    forecast_data = {}
    for asset in ("BTC", "ETH"):
        base = Path(f"results/main/{asset.lower()}_cryptobert")
        config = json.loads(source(base / "run_config.json").read_text())
        assert config["cryptobert_input_dim"] == 768 and config["cryptobert_pca_k"] is None
        assert config["lr_ts_scale"] == 0 and config["aux_weight"] == 0
        news_asset = news[news.asset == asset].reset_index(drop=True)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            retained = ~tag_based_recap_mask(news_asset)
        times = news_asset.unix_timestamp.to_numpy(np.int64)
        pre2026 = times < pd.Timestamp("2026-01-01", tz="UTC").timestamp()
        embdata = np.load(source(f"data/processed/{asset.lower()}_news_embeddings_cryptobert.npz"))
        assert np.array_equal(times, embdata["timestamps"]), "Embedding row alignment mismatch"
        emb = embdata["embeddings"]
        assert emb.shape == (len(times), 768)
        np.testing.assert_allclose(np.linalg.norm(emb, axis=1), 1, atol=1e-5)
        # Use the first raw timestamp, exactly as the price loader does, rather
        # than assuming every saved bar label coincides with a raw observation.
        price_config = cfg(asset)
        price_paths = price_config.get("price_files") or [price_config["price"]]
        raw_times = pd.concat([pd.read_csv(source(p), usecols=["timestamp"]) for p in price_paths], ignore_index=True)
        raw_seconds = raw_times.timestamp.to_numpy()
        bar_times = pd.Series(raw_seconds, index=pd.to_datetime(raw_seconds, unit="s", utc=True)).resample("15min").first()
        del raw_times, raw_seconds
        corp.append(dict(asset=asset, articles=len(times), retained=int(retained.sum()),
                         pre2026=int(pre2026.sum()), retained_pre2026=int((retained & pre2026).sum()),
                         earliest=str(pd.to_datetime(times.min(), unit="s", utc=True)),
                         latest=str(pd.to_datetime(times.max(), unit="s", utc=True))))
        archived = pd.read_csv(source(base / "expanding_window_metrics.csv"))
        archived_dm = pd.read_csv(source(base / "dm_test_results.csv"))
        pooled = {h: {k: [[], []] for k in MODELS} for h in ("1h", "4h")}
        for window in range(1, 7):
            meta = np.load(source(base / f"metadata/window_{window}_meta.npz"))
            for h in ("1h", "4h"):
                data = np.load(source(base / f"predictions/window_{window}_{h}_predictions.npz"), allow_pickle=True)
                actual = data["actual"]
                dates = pd.to_datetime(data["datetime"], utc=True)
                assert dates.is_monotonic_increasing and dates.is_unique
                assert len(actual) == len(meta["test_idx"])
                assert np.array_equal(data["test_idx"], meta["test_idx"])
                if h == "1h":
                    splitrows.append(dict(asset=asset, window=window,
                        train_N=len(meta["train_idx"]), val_N=len(meta["val_idx"]), test_N=len(actual),
                        test_start=str(dates[0]), test_end=str(dates[-1])))
                forecast_data[asset, h, window] = {k: data[k] for k in ("actual", "ts_mlp", "main_model")}
                forecast_data[asset, h, window]["dates"] = dates
                losses = {}
                for key, name in MODELS.items():
                    pred = data[key]
                    assert np.isfinite(pred).all() and (pred > 0).all()
                    m, ml, ql = metrics(pred, actual)
                    row = dict(asset=asset, window=window, horizon=h, model=name, N=len(actual), **m)
                    rows.append(row)
                    expected = archived[(archived.window == window) & (archived.horizon == h) & (archived.model == name)].iloc[0]
                    maxerr = max(abs(m[k] - expected[k]) for k in m)
                    assert maxerr < 2e-7, (asset, h, window, name, maxerr)
                    checks.append(dict(check="forecast_metrics", asset=asset, horizon=h, window=window, model=name, max_abs_error=maxerr))
                    # DM evaluation casts candidate forecasts to float64.
                    _, ml, ql = metrics(pred.astype(np.float64), actual)
                    losses[key] = (ml, ql)
                    pooled[h][key][0].append(ml)
                    pooled[h][key][1].append(ql)
                for lossnum, lossname in enumerate(("MSE", "QLIKE")):
                    stat, p = dm(losses["main_model"][lossnum], losses["ts_mlp"][lossnum], 4 if h == "1h" else 16)
                    dmrows.append(dict(asset=asset, horizon=h, window=str(window), loss=lossname, statistic=stat, p=p))
                state = torch.load(source(base / f"checkpoints/main_model_w{window}_{h}.pt"), map_location="cpu", weights_only=True)
                tsstate = torch.load(source(base / f"checkpoints/ts_mlp_w{window}_{h}.pt"), map_location="cpu", weights_only=True)
                p1state = torch.load(source(base / f"checkpoints/p1_model_w{window}_{h}.pt"), map_location="cpu", weights_only=True)
                assert float(state["ts_scale"]) == 1.0
                assert all(torch.equal(v, state[k]) and torch.equal(v, p1state[k]) for k, v in tsstate.items())
                assert state["news_head.0.weight"].shape == (128, 768)
                history = pd.read_csv(source(base / f"loss_curves/main_model_w{window}_{h}_loss.csv"))
                assert (history[history.phase == "P2"].ts_scale == 1).all()
                # One observation per article/checkpoint, only articles actually
                # eligible for at least one test forecast's 12-hour lookback.
                bar_seconds = bar_times.reindex(dates).to_numpy()
                assert np.isfinite(bar_seconds).all()
                bar_seconds = bar_seconds.astype(np.int64)
                first_after = np.searchsorted(bar_seconds, times, side="right")
                nearest = bar_seconds[np.minimum(first_after, len(bar_seconds) - 1)]
                used = retained & (first_after < len(bar_seconds)) & (nearest - times <= 43200)
                idx = np.flatnonzero(used)
                model = CryptoBertMainModel(768).eval()
                model.load_state_dict(state)
                with torch.no_grad():
                    output = model.news_head(model.input_norm(torch.from_numpy(emb[idx])))
                    s = torch.nn.functional.softplus(output[:, 0]).numpy()
                    lam = (.001 + .499 * torch.sigmoid(output[:, 1])).numpy()
                a, b = float(state["residual_head.weight"].item()), float(state["residual_head.bias"].item())
                for j, article in enumerate(idx):
                    parameters.append(dict(asset=asset, horizon=h, window=window, article_row=int(article),
                        timestamp=int(times[article]), s=float(s[j]), lambda_per_min=float(lam[j]),
                        half_life_min=float(np.log(2) / lam[j]), loading=a, intercept=b,
                        effective_initial_log_loading=float(a * s[j])))
        for h in ("1h", "4h"):
            for lossnum, lossname in enumerate(("MSE", "QLIKE")):
                stat, p = dm(np.concatenate(pooled[h]["main_model"][lossnum]),
                             np.concatenate(pooled[h]["ts_mlp"][lossnum]), 4 if h == "1h" else 16)
                dmrows.append(dict(asset=asset, horizon=h, window="all", loss=lossname, statistic=stat, p=p))
                expected = archived_dm[(archived_dm.window == "mean") & (archived_dm.horizon == h) & (archived_dm.model == "Main Model")].iloc[0]
                # Archived DM uses float32 TS references within windows and float64
                # pooled references. Only pooled values have exact dtype agreement.
                assert abs(stat - expected[f"DM_{lossname}_t_vs_TS_MLP"]) < 1e-5
                assert abs(p - expected[f"DM_{lossname}_p_vs_TS_MLP"]) < 1e-8
    frame, dmf, splits, corpus, pars = map(pd.DataFrame, (rows, dmrows, splitrows, corp, parameters))
    mean = frame.groupby(["asset", "horizon", "model"], as_index=False).agg(
        MSE=("MSE", "mean"), QLIKE=("QLIKE", "mean"), R2=("R2", "mean"), DA=("DA", "mean"), N=("N", "sum"))
    for asset in ("BTC", "ETH"):
        archived_mean = pd.read_csv(source(f"results/main/{asset.lower()}_cryptobert/expanding_window_mean_metrics.csv"))
        for row in archived_mean.to_dict("records"):
            found = mean[(mean.asset == asset) & (mean.horizon == row["horizon"]) & (mean.model == row["model"])].iloc[0]
            assert max(abs(found[k] - row[k]) for k in ("MSE", "QLIKE", "R2", "DA")) < 2e-7
    for name, df in (("metrics_per_window", frame), ("metrics_mean", mean), ("dm_ned_vs_ts", dmf),
                     ("splits", splits), ("corpus", corpus), ("article_parameters", pars), ("metric_checks", pd.DataFrame(checks))):
        df.to_csv(GEN / f"{name}.csv", index=False, float_format="%.12g")
    for h in ("1h", "4h"):
        tabrows = []
        for asset in ("BTC", "ETH"):
            for name in MODELS.values():
                r = mean[(mean.asset == asset) & (mean.horizon == h) & (mean.model == name)].iloc[0]
                tabrows.append([asset, DISPLAY.get(name, name)] + [f"{r[k]:.4f}" for k in ("R2", "DA", "QLIKE", "MSE")])
        table(f"performance_{h}.tex", "llrrrr", r"Asset & Model & $R^2$ & MA & QLIKE & Log-MSE", tabrows)
    improvements, impwindow = [], []
    for asset in ("BTC", "ETH"):
        for h in ("1h", "4h"):
            for w in ["mean"] + list(range(1, 7)):
                f = mean if w == "mean" else frame[frame.window == w]
                f = f[(f.asset == asset) & (f.horizon == h)].set_index("model")
                r = dict(asset=asset, horizon=h, window=w)
                for loss in ("MSE", "QLIKE"):
                    r[loss] = 100 * (1 - f.loc["Main Model", loss] / f.loc["TS MLP", loss])
                if w == "mean":
                    sub = dmf[(dmf.asset == asset) & (dmf.horizon == h) & (dmf.window == "all")].set_index("loss")
                    improvements.append([asset, h, f"{r['QLIKE']:+.2f}", f"{sub.loc['QLIKE', 'statistic']:.3f}", pformat(sub.loc['QLIKE', 'p']),
                                         f"{r['MSE']:+.2f}", f"{sub.loc['MSE', 'statistic']:.3f}", pformat(sub.loc['MSE', 'p'])])
                else:
                    impwindow.append(r)
    table("improvements.tex", "llrrrrrr", r"Asset & $H$ & QLIKE (\%) & DM & $p$ & MSE (\%) & DM & $p$", improvements)
    impwindow = pd.DataFrame(impwindow)
    impwindow.to_csv(GEN / "improvements_per_window.csv", index=False)
    for asset in ("BTC", "ETH"):
        tabrows = []
        for w in range(1, 7):
            for h in ("1h", "4h"):
                for name in MODELS.values():
                    r = frame[(frame.asset == asset) & (frame.window == w) & (frame.horizon == h) & (frame.model == name)].iloc[0]
                    tabrows.append([w, h, DISPLAY.get(name, name), int(r.N)] + [f"{r[k]:.4f}" for k in ("R2", "DA", "QLIKE", "MSE")])
        heading = r"Window & $H$ & Model & $N$ & $R^2$ & MA & QLIKE & Log-MSE"
        table(f"per_window_{asset.lower()}.tex", "rllrrrrr", heading, tabrows)
        path = GEN / f"per_window_{asset.lower()}.tex"
        text = path.read_text().replace("tabular", "longtable")
        text = text.replace(r"\midrule", r"\midrule" + "\n" + r"\endfirsthead" + "\n" + r"\toprule" + "\n" + heading + r" \\" + "\n" + r"\midrule\endhead", 1)
        path.write_text(text)
    table("splits.tex", "rllrrrr", r"Window & Validation & Test & BTC train & ETH train & BTC test & ETH test",
          [[w, WINDOWS[w + 1][0][:7] + "--" + WINDOWS[w + 1][1][:7],
            WINDOWS[w + 1][2][:7] + "--" + WINDOWS[w + 1][3][:7],
            *[int(splits[(splits.asset == a) & (splits.window == w)].iloc[0].train_N) for a in ("BTC", "ETH")],
            *[int(splits[(splits.asset == a) & (splits.window == w)].iloc[0].test_N) for a in ("BTC", "ETH")]] for w in range(1, 7)])
    table("corpus.tex", "lrrrr", r"Asset & All dates & Retained & Before 2026 & Retained before 2026",
          [[r.asset, r.articles, r.retained, r.pre2026, r.retained_pre2026] for r in corpus.itertuples()])
    summary = pars.groupby(["asset", "horizon"]).agg(N=("s", "size"), s_median=("s", "median"),
        half_q25=("half_life_min", lambda x: x.quantile(.25)), half_median=("half_life_min", "median"),
        half_q75=("half_life_min", lambda x: x.quantile(.75)),
        effective_median=("effective_initial_log_loading", "median")).reset_index()
    summary.to_csv(GEN / "parameter_summary.csv", index=False)
    table("parameters.tex", "llrrrr", r"Asset & $H$ & Article--window pairs & $h_{1/2}$ Q25 & Median & Q75",
          [[r.asset, r.horizon, int(r.N), f"{r.half_q25:.1f}", f"{r.half_median:.1f}", f"{r.half_q75:.1f}"] for r in summary.itertuples()])
    # Post-hoc outcome strata: standardize log actuals separately in each test window.
    decile_data = []
    for w in range(1, 7):
        d = forecast_data["BTC", "4h", w]
        y = np.log(d["actual"] + EPS)
        decile_data.append(pd.DataFrame(dict(z=(y-y.mean()) / y.std(ddof=0), actual=d["actual"], ts=d["ts_mlp"], ned=d["main_model"])))
    dec = pd.concat(decile_data, ignore_index=True)
    dec["decile"] = pd.qcut(dec.z, 10, labels=False) + 1
    drows = []
    for group, d in dec.groupby("decile"):
        ts, _, _ = metrics(d.ts.to_numpy(), d.actual.to_numpy())
        ned, _, _ = metrics(d.ned.to_numpy(), d.actual.to_numpy())
        drows.append(dict(decile=group, N=len(d), z_mean=d.z.mean(), ts_R2=ts["R2"], ned_R2=ned["R2"],
                          QLIKE_improvement=100*(1-ned["QLIKE"]/ts["QLIKE"]), MSE_improvement=100*(1-ned["MSE"]/ts["MSE"])))
    deciles = pd.DataFrame(drows)
    deciles.to_csv(GEN / "btc_4h_deciles.csv", index=False)
    table("deciles.tex", "rrrrrrr", r"Decile & $N$ & Mean $z$ & TS $R^2$ & NED $R^2$ & QLIKE (\%) & MSE (\%)",
          [[int(r.decile), int(r.N), f"{r.z_mean:.2f}", f"{r.ts_R2:.3f}", f"{r.ned_R2:.3f}",
            f"{r.QLIKE_improvement:+.2f}", f"{r.MSE_improvement:+.2f}"] for r in deciles.itertuples()])
    plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})
    fig, axes = plt.subplots(2, 2, figsize=(10, 6), sharex=True, constrained_layout=True)
    for i, asset in enumerate(("BTC", "ETH")):
        for j, loss in enumerate(("QLIKE", "MSE")):
            ax = axes[i, j]
            for h, marker in (("1h", "o"), ("4h", "s")):
                d = impwindow[(impwindow.asset == asset) & (impwindow.horizon == h)]
                ax.plot(d.window, d[loss], marker=marker, label=h)
            ax.axhline(0, color="0.5", lw=.8)
            ax.set(title=f"{asset}: {loss}", ylabel="Reduction vs TS-only (%)", xticks=range(1, 7))
            if i == 1: ax.set_xlabel("Test window")
            ax.legend(frameon=False)
    fig.savefig(FIG / "window_improvements.pdf")
    plt.close(fig)
    fig, axes = plt.subplots(1, 2, figsize=(10, 4), constrained_layout=True)
    btc = pars[(pars.asset == "BTC") & (pars.horizon == "4h")]
    axes[0].scatter(btc.s, btc.lambda_per_min, s=3, alpha=.25, rasterized=True)
    axes[0].set(xlabel="Raw article magnitude s", ylabel="Decay rate (per minute)", yscale="log")
    for asset, color in (("BTC", "#167c80"), ("ETH", "#c15b30")):
        d = pars[(pars.asset == asset) & (pars.horizon == "4h")].half_life_min
        axes[1].hist(d, bins=np.geomspace(1.3, 700, 35), density=True, histtype="step", lw=1.5, label=asset, color=color)
    axes[1].set(xscale="log", xlabel="Learned half-life (minutes), 4h models", ylabel="Density per minute")
    axes[1].legend(frameon=False)
    fig.savefig(FIG / "learned_parameters.pdf")
    plt.close(fig)
    for path in ("main_model_common.py", "main_model_cryptobert.py", "expanding_window_btc.py", "expanding_window_eth.py",
                 "step2_btc_cryptobert.py", "step2_eth_cryptobert.py", "python expanding_window_eth.py 09021815.txt"):
        source(path)
    manifest = {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(inputs)}
    (GEN / "source_sha256.json").write_text(json.dumps(manifest, indent=2) + "\n")
    report = dict(prediction_files=24, metric_rows=len(frame), metric_max_abs_error=max(r["max_abs_error"] for r in checks),
                  input_files=len(inputs), ts_checkpoints_equal=True, ts_scale_all_one=True,
                  embedding_alignment=True, pca_used=False, article_window_pairs=len(pars))
    (GEN / "audit_summary.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))
    print(summary.to_string(index=False))
    print("All forecast, mean-metric, pooled-DM, and checkpoint checks passed.")


if __name__ == "__main__":
    main()
